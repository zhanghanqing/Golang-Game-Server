// Roles, ports and label keys shared by the generated objects.
const (
	roleGate  = "gate"
	roleLogin = "login"
	roleGame  = "game"

	portTCP   = 7000
	portWS    = 7001
	portAdmin = 9100

	labelName      = "app.kubernetes.io/name"
	labelInstance  = "app.kubernetes.io/instance"
	labelComponent = "app.kubernetes.io/component"
	labelManagedBy = "app.kubernetes.io/managed-by"
	labelVersion   = "gameserver.dev/version"

	// annotationDrain marks a game pod as draining; the value is the RFC 3339
	// start time. It is the operator's durable record of the decision, so a
	// restarted operator continues the drain where it left off.
	annotationDrain = "gameserver.dev/drain-started"
	// annotationConfig rolls gate and login pods when their config changes.
	annotationConfig = "gameserver.dev/config-hash"

	configMountPath = "/etc/gameserver"
)

// withDefaults fills optional fields. The CRD applies the same defaults on
// the API server; repeating them here keeps the controller correct for
// objects created without them (and in unit tests).
func withDefaults(s gsv1.GameClusterSpec) gsv1.GameClusterSpec {
	if s.ImagePullPolicy == "" {
		s.ImagePullPolicy = corev1.PullIfNotPresent
	}
	if s.Infra.MongoDatabase == "" {
		s.Infra.MongoDatabase = "game"
	}
	if s.Gate.Replicas <= 0 {
		s.Gate.Replicas = 2
	}
	if s.Gate.ServiceType == "" {
		s.Gate.ServiceType = corev1.ServiceTypeClusterIP
	}
	if s.Login.Replicas <= 0 {
		s.Login.Replicas = 1
	}
	if s.Game.DrainTimeout.Duration <= 0 {
		s.Game.DrainTimeout.Duration = 5 * time.Minute
	}
	if a := s.Game.Autoscale; a != nil {
		a = a.DeepCopy()
		if a.ScaleDownDelay.Duration <= 0 {
			a.ScaleDownDelay.Duration = 2 * time.Minute
		}
		s.Game.Autoscale = a
	}
	if s.LogLevel == "" {
		s.LogLevel = "info"
	}
	return s
}

// ---------------------------------------------------------------------------
// Names and labels

func configMapName(gc *gsv1.GameCluster) string { return gc.Name + "-config" }
func gateName(gc *gsv1.GameCluster) string      { return gc.Name + "-gate" }
func loginName(gc *gsv1.GameCluster) string     { return gc.Name + "-login" }

// newGamePodName returns a fresh pod name. The pod name is also the game
// node id, so it must be unique for the lifetime of the cluster.
func newGamePodName(gc *gsv1.GameCluster) string {
	return gc.Name + "-game-" + rand.String(5)
}

func selectorLabels(gc *gsv1.GameCluster, role string) map[string]string {
	return map[string]string{
		labelName:      "gameserver",
		labelInstance:  gc.Name,
		labelComponent: role,
	}
}

func commonLabels(gc *gsv1.GameCluster, role string) map[string]string {
	l := selectorLabels(gc, role)
	l[labelManagedBy] = "gameserver-operator"
	return l
}

// ---------------------------------------------------------------------------
// Configuration

// renderConfigs returns one server config file per role. Node ids and the
// Snowflake worker id differ per pod, so they are left as ${ENV} placeholders
// that the server expands at startup.
func renderConfigs(spec gsv1.GameClusterSpec) map[string]string {
	q := strconv.Quote
	common := func(role, extra string) string {
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by gameserver-operator. Do not edit.\n")
		fmt.Fprintf(&b, "node:\n  id: ${NODE_ID}\n  roles: [%s]\n%s", role, extra)
		fmt.Fprintf(&b, "log:\n  level: %s\n  format: json\n", q(spec.LogLevel))
		fmt.Fprintf(&b, "cluster:\n  bus: nats\n  nats_url: %s\n  registry: redis\n  registry_ttl: 10s\n", q(spec.Infra.NatsURL))
		fmt.Fprintf(&b, "redis:\n  addr: %s\n", q(spec.Infra.RedisAddr))
		fmt.Fprintf(&b, "admin:\n  addr: \"0.0.0.0:%d\"\n", portAdmin)
		return b.String()
	}
	mongo := fmt.Sprintf("storage:\n  driver: mongo\nmongo:\n  uri: %s\n  database: %s\n",
		q(spec.Infra.MongoURI), q(spec.Infra.MongoDatabase))

	gate := common(roleGate, "") + fmt.Sprintf(
		"console:\n  enabled: %t\ngate:\n  tcp_addr: \":%d\"\n  ws_addr: \":%d\"\n  ws_path: /ws\n  max_conns: 20000\n  idle_timeout: 60s\n  rate_limit: 50\n  rate_burst: 100\n",
		spec.Gate.Console, portTCP, portWS)
	login := common(roleLogin, "  worker_id: ${WORKER_ID}\n") + mongo +
		"login:\n  bcrypt_cost: 10\n  max_concurrent: 256\n"
	game := common(roleGame, "") + mongo + fmt.Sprintf(
		"game:\n  save_interval: 30s\n  gm_enabled: %t\n  chat_interval: 1s\n  max_move_step: 50\n", spec.Game.GMEnabled)

	return map[string]string{roleGate + ".yaml": gate, roleLogin + ".yaml": login, roleGame + ".yaml": game}
}

// hashOf returns a short stable hash of v (JSON encoded).
func hashOf(v any) string {
	b, _ := json.Marshal(v)
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])[:10]
}

// gameVersion identifies the game pod template. Any change in it makes
// existing game nodes "outdated" and starts a rolling update.
func gameVersion(spec gsv1.GameClusterSpec, configs map[string]string) string {
	return hashOf(struct {
		Image     string
		Pull      corev1.PullPolicy
		Config    string
		Resources corev1.ResourceRequirements
	}{spec.Image, spec.ImagePullPolicy, configs[roleGame+".yaml"], spec.Game.Resources})
}

// ---------------------------------------------------------------------------
// Pod template

// podSpec is the shared pod spec of every role.
func podSpec(gc *gsv1.GameCluster, spec gsv1.GameClusterSpec, role string, res corev1.ResourceRequirements, extraEnv []corev1.EnvVar, ports []corev1.ContainerPort) corev1.PodSpec {
	env := append([]corev1.EnvVar{{
		Name:      "NODE_ID",
		ValueFrom: &corev1.EnvVarSource{FieldRef: &corev1.ObjectFieldSelector{FieldPath: "metadata.name"}},
	}}, extraEnv...)
	ports = append(ports, corev1.ContainerPort{Name: "admin", ContainerPort: portAdmin})
	probe := func(path string, period int32) *corev1.Probe {
		return &corev1.Probe{
			ProbeHandler: corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{
				Path: path, Port: intstr.FromString("admin"),
			}},
			PeriodSeconds:    period,
			FailureThreshold: 3,
		}
	}
	return corev1.PodSpec{
		// Game nodes need time to save every player on SIGTERM.
		TerminationGracePeriodSeconds: ptr.To[int64](60),
		SecurityContext: &corev1.PodSecurityContext{
			RunAsNonRoot:   ptr.To(true),
			SeccompProfile: &corev1.SeccompProfile{Type: corev1.SeccompProfileTypeRuntimeDefault},
		},
		Containers: []corev1.Container{{
			Name:            "server",
			Image:           spec.Image,
			ImagePullPolicy: spec.ImagePullPolicy,
			Args:            []string{"-config", configMountPath + "/" + role + ".yaml"},
			Env:             env,
			Ports:           ports,
			Resources:       res,
			ReadinessProbe:  probe("/readyz", 5),
			LivenessProbe:   probe("/healthz", 10),
			StartupProbe: &corev1.Probe{
				ProbeHandler:     corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: "/healthz", Port: intstr.FromString("admin")}},
				PeriodSeconds:    2,
				FailureThreshold: 30,
			},
			SecurityContext: &corev1.SecurityContext{
				AllowPrivilegeEscalation: ptr.To(false),
				ReadOnlyRootFilesystem:   ptr.To(true),
				Capabilities:             &corev1.Capabilities{Drop: []corev1.Capability{"ALL"}},
			},
			VolumeMounts: []corev1.VolumeMount{{Name: "config", MountPath: configMountPath, ReadOnly: true}},
		}},
		Volumes: []corev1.Volume{{
			Name: "config",
			VolumeSource: corev1.VolumeSource{ConfigMap: &corev1.ConfigMapVolumeSource{
				LocalObjectReference: corev1.LocalObjectReference{Name: configMapName(gc)},
			}},
		}},
	}
}

// ---------------------------------------------------------------------------
// Objects. The mutate functions set only the fields the operator owns, so
// they can run on both new and existing objects (controllerutil.CreateOrUpdate).

func mutateConfigMap(cm *corev1.ConfigMap, gc *gsv1.GameCluster, configs map[string]string) {
	cm.Labels = commonLabels(gc, "config")
	cm.Data = configs
}

func mutateGateDeployment(d *appsv1.Deployment, gc *gsv1.GameCluster, spec gsv1.GameClusterSpec, configHash string) {
	d.Labels = commonLabels(gc, roleGate)
	if d.CreationTimestamp.IsZero() {
		d.Spec.Selector = &metav1.LabelSelector{MatchLabels: selectorLabels(gc, roleGate)}
	}
	d.Spec.Replicas = ptr.To(spec.Gate.Replicas)
	d.Spec.Strategy = appsv1.DeploymentStrategy{
		Type: appsv1.RollingUpdateDeploymentStrategyType,
		RollingUpdate: &appsv1.RollingUpdateDeployment{
			MaxUnavailable: ptr.To(intstr.FromInt32(0)),
			MaxSurge:       ptr.To(intstr.FromInt32(1)),
		},
	}
	d.Spec.Template.Labels = commonLabels(gc, roleGate)
	d.Spec.Template.Annotations = map[string]string{annotationConfig: configHash}
	d.Spec.Template.Spec = podSpec(gc, spec, roleGate, spec.Gate.Resources, nil, []corev1.ContainerPort{
		{Name: "tcp", ContainerPort: portTCP},
		{Name: "ws", ContainerPort: portWS},
	})
}

func mutateGateService(svc *corev1.Service, gc *gsv1.GameCluster, spec gsv1.GameClusterSpec) {
	svc.Labels = commonLabels(gc, roleGate)
	svc.Spec.Type = spec.Gate.ServiceType
	svc.Spec.Selector = selectorLabels(gc, roleGate)
	// Keep node ports the API server assigned; only set what we own.
	want := map[string]int32{"tcp": portTCP, "ws": portWS}
	ports := make([]corev1.ServicePort, 0, len(want))
	for _, name := range []string{"tcp", "ws"} {
		p := corev1.ServicePort{Name: name, Port: want[name], TargetPort: intstr.FromString(name), Protocol: corev1.ProtocolTCP}
		for _, old := range svc.Spec.Ports {
			if old.Name == name && spec.Gate.ServiceType != corev1.ServiceTypeClusterIP {
				p.NodePort = old.NodePort
			}
		}
		ports = append(ports, p)
	}
	svc.Spec.Ports = ports
}

func mutateLoginService(svc *corev1.Service, gc *gsv1.GameCluster) {
	svc.Labels = commonLabels(gc, roleLogin)
	svc.Spec.ClusterIP = corev1.ClusterIPNone // headless: required by the StatefulSet
	svc.Spec.Selector = selectorLabels(gc, roleLogin)
	svc.Spec.Ports = []corev1.ServicePort{{Name: "admin", Port: portAdmin, TargetPort: intstr.FromString("admin")}}
}

func mutateLoginStatefulSet(s *appsv1.StatefulSet, gc *gsv1.GameCluster, spec gsv1.GameClusterSpec, configHash string) {
	s.Labels = commonLabels(gc, roleLogin)
	if s.CreationTimestamp.IsZero() {
		s.Spec.Selector = &metav1.LabelSelector{MatchLabels: selectorLabels(gc, roleLogin)}
		s.Spec.ServiceName = loginName(gc)
	}
	s.Spec.Replicas = ptr.To(spec.Login.Replicas)
	// Login pods are interchangeable; start them all at once.
	s.Spec.PodManagementPolicy = appsv1.ParallelPodManagement
	s.Spec.Template.Labels = commonLabels(gc, roleLogin)
	s.Spec.Template.Annotations = map[string]string{annotationConfig: configHash}
	// The StatefulSet pod index (0, 1, 2...) is unique and stable, which is
	// exactly what a Snowflake worker id needs.
	workerID := corev1.EnvVar{
		Name: "WORKER_ID",
		ValueFrom: &corev1.EnvVarSource{FieldRef: &corev1.ObjectFieldSelector{
			FieldPath: "metadata.labels['apps.kubernetes.io/pod-index']",
		}},
	}
	s.Spec.Template.Spec = podSpec(gc, spec, roleLogin, spec.Login.Resources, []corev1.EnvVar{workerID}, nil)
}

// newGamePod builds one game node. Game pods are created directly (not by a
// Deployment) so the operator decides which one to remove, and when.
func newGamePod(gc *gsv1.GameCluster, spec gsv1.GameClusterSpec, version string) *corev1.Pod {
	labels := commonLabels(gc, roleGame)
	labels[labelVersion] = version
	return &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{
			Name:      newGamePodName(gc),
			Namespace: gc.Namespace,
			Labels:    labels,
		},
		Spec: podSpec(gc, spec, roleGame, spec.Game.Resources, nil, nil),
	}
}
